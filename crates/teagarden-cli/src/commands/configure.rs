use anyhow::{Context, Result};
use std::io::{self, BufRead, Write};
use std::path::{Path, PathBuf};

fn prompt(question: &str) -> Result<String> {
    print!("{question} ");
    io::stdout().flush()?;
    let mut input = String::new();
    io::stdin()
        .lock()
        .read_line(&mut input)
        .context("failed to read input")?;
    Ok(input.trim().to_string())
}

fn prompt_default(question: &str, default: &str) -> Result<String> {
    print!("{question} [{default}]: ");
    io::stdout().flush()?;
    let mut input = String::new();
    io::stdin()
        .lock()
        .read_line(&mut input)
        .context("failed to read input")?;
    let trimmed = input.trim();
    if trimmed.is_empty() {
        Ok(default.to_string())
    } else {
        Ok(trimmed.to_string())
    }
}

fn prompt_yes_no(question: &str, default_yes: bool) -> Result<bool> {
    let hint = if default_yes { "Y/n" } else { "y/N" };
    let answer = prompt(&format!("{question} ({hint})"))?;
    if answer.is_empty() {
        return Ok(default_yes);
    }
    Ok(matches!(answer.to_lowercase().as_str(), "y" | "yes"))
}

fn config_dir() -> Result<PathBuf> {
    super::utils::config_dir()
}

fn env_file_path() -> Result<PathBuf> {
    Ok(config_dir()?.join(".env"))
}

/// The layout of a newly created `.env`, with the keys `configure` owns empty.
const NEW_ENV_TEMPLATE: &str = "# TeaGarden Configuration\n\
# Generated by `teagarden configure`\n\
#\n\
# Telegram API credentials - DO NOT share these\n\
TG_API_ID=\n\
TG_API_HASH=\n\
\n\
# Storage paths\n\
TEAGARDEN_VOLUMES_DIR=\n\
TEAGARDEN_SESSION_PATH=\n";

/// The `KEY` of a `KEY=value` (or `export KEY=value`) line, without its line
/// terminator. `None` for comments, blanks and anything without an `=`.
fn line_key(line: &[u8]) -> Option<&[u8]> {
    let line = line.trim_ascii_start();
    let line = line
        .strip_prefix(b"export ")
        .map_or(line, <[u8]>::trim_ascii_start);
    let eq = line.iter().position(|&b| b == b'=')?;
    Some(line[..eq].trim_ascii_end())
}

/// Set each `(key, value)` of `owned` in `existing` (the bytes of a `.env`) and
/// carry every other byte over unchanged: bot tokens, comments, unknown keys,
/// line endings, a missing final newline. A line for an owned key is replaced in
/// place and keeps its own line terminator; an owned key not yet present is
/// appended. An empty `existing` starts from [`NEW_ENV_TEMPLATE`].
pub(crate) fn merge_owned_keys(existing: &[u8], owned: &[(&str, &str)]) -> Vec<u8> {
    let base = if existing.is_empty() {
        NEW_ENV_TEMPLATE.as_bytes()
    } else {
        existing
    };
    let mut out = Vec::with_capacity(base.len() + 256);
    let mut seen = vec![false; owned.len()];
    for line in base.split_inclusive(|&b| b == b'\n') {
        let body_len = line.strip_suffix(b"\n").map_or(line.len(), |l| {
            l.strip_suffix(b"\r").map_or(l.len(), |l| l.len())
        });
        let hit = line_key(&line[..body_len])
            .and_then(|k| owned.iter().position(|(name, _)| name.as_bytes() == k));
        match hit {
            Some(i) => {
                seen[i] = true;
                out.extend_from_slice(format!("{}={}", owned[i].0, owned[i].1).as_bytes());
                out.extend_from_slice(&line[body_len..]);
            }
            None => out.extend_from_slice(line),
        }
    }
    for (i, (key, value)) in owned.iter().enumerate() {
        if seen[i] {
            continue;
        }
        if !out.is_empty() && !out.ends_with(b"\n") {
            out.push(b'\n');
        }
        out.extend_from_slice(format!("{key}={value}\n").as_bytes());
    }
    out
}

/// Remove every line whose key is one of `keys`, carrying every other byte over
/// unchanged. Used by `auth export` / `auth import` to leave out settings that
/// name a path on one computer.
pub(crate) fn drop_keys(existing: &[u8], keys: &[&str]) -> Vec<u8> {
    let mut out = Vec::with_capacity(existing.len());
    for line in existing.split_inclusive(|&b| b == b'\n') {
        let body_len = line.strip_suffix(b"\n").map_or(line.len(), |l| {
            l.strip_suffix(b"\r").map_or(l.len(), |l| l.len())
        });
        let drop = line_key(&line[..body_len])
            .is_some_and(|k| keys.iter().any(|name| name.as_bytes() == k));
        if !drop {
            out.extend_from_slice(line);
        }
    }
    out
}

/// The value of `key` in `existing` (the bytes of a `.env`): the last
/// assignment wins, an `export ` prefix and spaces around `=` are accepted, and an
/// empty or non-UTF-8 value counts as unset.
pub(crate) fn env_value(existing: &[u8], key: &str) -> Option<String> {
    let mut found = None;
    for line in existing.split_inclusive(|&b| b == b'\n') {
        let line = line.strip_suffix(b"\n").unwrap_or(line);
        let line = line.strip_suffix(b"\r").unwrap_or(line);
        if line_key(line) != Some(key.as_bytes()) {
            continue;
        }
        let eq = line.iter().position(|&b| b == b'=')?;
        found = std::str::from_utf8(&line[eq + 1..])
            .ok()
            .map(|v| v.trim().to_string())
            .filter(|v| !v.is_empty());
    }
    found
}

pub async fn run() -> Result<()> {
    println!();
    println!("  ╔══════════════════════════════════════╗");
    println!("  ║     TeaGarden Configuration Setup    ║");
    println!("  ╚══════════════════════════════════════╝");
    println!();

    // Step 1: Check existing config
    let env_path = env_file_path()?;
    if env_path.exists() {
        println!("  Existing configuration found at: {}", env_path.display());
        let existing = std::fs::read_to_string(&env_path)?;
        println!();
        for line in existing.lines() {
            if line.starts_with('#') || line.is_empty() {
                continue;
            }
            if let Some(shown) = display_env_line(line) {
                println!("  Current: {shown}");
            }
        }
        println!();
        println!("  Only the Telegram API and storage-path settings are replaced; bot");
        println!("  tokens, comments and every other line in the file are kept.");
        println!();
        if !prompt_yes_no("  Update the existing configuration?", false)? {
            println!("  Keeping existing configuration.");
            return Ok(());
        }
        println!();
    }

    // Step 2: Telegram API credentials
    println!("  Step 1: Telegram API Credentials");
    println!("  ─────────────────────────────────");
    println!("  TeaGarden uses Telegram as encrypted block storage.");
    println!("  You need API credentials from https://my.telegram.org");
    println!();
    println!("  How to get them:");
    println!("    1. Open https://my.telegram.org in your browser");
    println!("    2. Log in with your phone number");
    println!("    3. Click 'API development tools'");
    println!("    4. Fill in the form (app name/platform don't matter)");
    println!("    5. Copy api_id and api_hash");
    println!();

    let open_browser = prompt_yes_no("  Open https://my.telegram.org in your browser?", true)?;
    if open_browser {
        let _ = open_url("https://my.telegram.org");
        println!();
        println!("  Browser opened. Complete the steps above, then enter your credentials.");
        println!();
    }

    let api_id = loop {
        let input = prompt("  Telegram API ID (number):")?;
        if input.is_empty() {
            println!("  API ID is required.");
            continue;
        }
        match input.parse::<i32>() {
            Ok(id) if id > 0 => break id,
            _ => {
                println!("  Invalid API ID. Must be a positive number.");
                continue;
            }
        }
    };

    // The hash is a credential: read it with echo off, never show it as typed.
    let api_hash = loop {
        let input =
            super::utils::prompt_hidden("  Telegram API Hash (32 hex characters, hidden): ")?;
        println!();
        match super::utils::validate_api_hash(&input) {
            Ok(()) => break input,
            Err(e) => println!("  {e}"),
        }
    };

    println!();

    // Step 3: Volumes directory
    println!("  Step 2: Storage Location");
    println!("  ────────────────────────");
    let default_volumes_dir = dirs::data_dir()
        .unwrap_or_else(|| PathBuf::from("~/.local/share"))
        .join("teagarden")
        .join("volumes");
    let volumes_dir = prompt_default(
        "  Volumes directory:",
        &default_volumes_dir.to_string_lossy(),
    )?;

    println!();

    // Step 4: Session file
    println!("  Step 3: Session Storage");
    println!("  ───────────────────────");
    let default_session = config_dir()?.join("teagarden.session");
    let session_path = prompt_default(
        "  Telegram session file:",
        &default_session.to_string_lossy(),
    )?;

    println!();

    // Step 5: Write config
    println!("  Step 4: Writing Configuration");
    println!("  ─────────────────────────────");

    let config_path = config_dir()?;
    // Both directories hold secrets: 0700 whatever the umask.
    teagarden_core::fsutil::ensure_private_dir(&config_path)
        .with_context(|| format!("failed to create config dir: {}", config_path.display()))?;

    teagarden_core::fsutil::ensure_private_dir(Path::new(&volumes_dir))
        .with_context(|| format!("failed to create volumes dir: {volumes_dir}"))?;

    if let Some(parent) = Path::new(&session_path).parent() {
        std::fs::create_dir_all(parent)?;
    }

    let api_id = api_id.to_string();
    let owned = [
        ("TG_API_ID", api_id.as_str()),
        ("TG_API_HASH", api_hash.as_str()),
        ("TEAGARDEN_VOLUMES_DIR", volumes_dir.as_str()),
        ("TEAGARDEN_SESSION_PATH", session_path.as_str()),
    ];
    // The `.env` also holds the storage-bot tokens (`TELEGRAM_BOT_TOKEN_N`) and
    // whatever else the user keeps there: update only our keys, under the same
    // lock and atomic write `volume add-bot` uses (mode 0600, fsynced, renamed).
    super::bot_env::rewrite(&env_path, |existing| merge_owned_keys(existing, &owned))
        .with_context(|| format!("failed to write {}", env_path.display()))?;

    println!("  Config written to: {}", env_path.display());
    println!("  Permissions: 600 (owner read/write only)");
    println!();

    // No shell integration: TeaGarden reads this file itself on every run, so it
    // never needs to be sourced. Sourcing it from a startup file would export the
    // API hash and any bot tokens into every shell and every program started
    // from it, so the wizard neither offers that nor suggests it.
    println!("  TeaGarden reads this file itself on every run. Do not load it into your");
    println!("  shell from a startup file: that would hand the API hash and bot tokens");
    println!("  to every program you start.");
    println!();
    println!("  ╔══════════════════════════════════════╗");
    println!("  ║        Configuration Complete!        ║");
    println!("  ╚══════════════════════════════════════╝");
    println!();
    println!("  Next steps:");
    println!("    1. Authenticate: teagarden auth login");
    println!("    2. Create a volume: teagarden volume create --name my-vault");
    println!("    3. Optional, tab completion: teagarden completions <bash|zsh|fish> --install");
    println!();

    Ok(())
}

fn open_url(url: &str) -> Result<()> {
    #[cfg(target_os = "macos")]
    {
        std::process::Command::new("open").arg(url).spawn()?;
    }
    #[cfg(target_os = "linux")]
    {
        std::process::Command::new("xdg-open").arg(url).spawn()?;
    }
    #[cfg(target_os = "windows")]
    {
        std::process::Command::new("cmd")
            .args(["/c", "start", url])
            .spawn()?;
    }
    Ok(())
}

/// Keys whose values are not secret and may be echoed back to the terminal.
/// Every other key in the env file is shown as `KEY=****`: the file holds the
/// Telegram API hash and bot tokens, and anything unrecognised is assumed secret.
const NON_SECRET_KEYS: &[&str] = &[
    "TG_API_ID",
    "TEAGARDEN_VOLUMES_DIR",
    "TEAGARDEN_SESSION_PATH",
];

/// How one `.env` line is shown by `configure`, or `None` if it is not `KEY=value`.
fn display_env_line(line: &str) -> Option<String> {
    let (key, _) = line.split_once('=')?;
    let bare = key.trim().trim_start_matches("export ").trim();
    if NON_SECRET_KEYS.contains(&bare) {
        Some(line.to_string())
    } else {
        Some(format!("{}=****", key.trim_end()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn configure_never_echoes_a_secret_value() {
        for line in [
            "TG_API_HASH=0123456789abcdef0123456789abcdef",
            "TELEGRAM_BOT_TOKEN_1=123456:AAAA-secret",
            "SOME_PASSWORD=hunter2",
            "export TELEGRAM_BOT_TOKEN_2 = 99:BBBB",
        ] {
            let shown = display_env_line(line).unwrap();
            let value = line.split_once('=').unwrap().1.trim();
            assert!(!shown.contains(value), "{line:?} shown as {shown:?}");
            assert!(shown.ends_with("=****"), "{shown:?}");
        }
        assert_eq!(
            display_env_line("TG_API_ID=12345").as_deref(),
            Some("TG_API_ID=12345")
        );
        assert_eq!(display_env_line("no equals sign"), None);
    }

    #[test]
    fn a_new_env_file_has_the_documented_layout() {
        let out = merge_owned_keys(
            b"",
            &[
                ("TG_API_ID", "7"),
                ("TG_API_HASH", "abc"),
                ("TEAGARDEN_VOLUMES_DIR", "/v"),
                ("TEAGARDEN_SESSION_PATH", "/s"),
            ],
        );
        assert_eq!(
            String::from_utf8(out).unwrap(),
            "# TeaGarden Configuration\n# Generated by `teagarden configure`\n#\n\
             # Telegram API credentials - DO NOT share these\nTG_API_ID=7\nTG_API_HASH=abc\n\n\
             # Storage paths\nTEAGARDEN_VOLUMES_DIR=/v\nTEAGARDEN_SESSION_PATH=/s\n"
        );
    }

    #[test]
    fn merging_twice_is_stable_and_handles_export_and_duplicates() {
        let owned = [("TG_API_ID", "9")];
        let once = merge_owned_keys(b"export TG_API_ID = 1\nX=1\nTG_API_ID=2\r\n", &owned);
        assert_eq!(once, b"TG_API_ID=9\nX=1\nTG_API_ID=9\r\n");
        assert_eq!(merge_owned_keys(&once, &owned), once);
    }

    #[test]
    fn non_utf8_bytes_in_other_lines_survive() {
        let existing = b"BIN=\xff\xfe\nTG_API_ID=1\n";
        let out = merge_owned_keys(existing, &[("TG_API_ID", "2")]);
        assert_eq!(out, b"BIN=\xff\xfe\nTG_API_ID=2\n");
    }

    #[test]
    fn dropping_keys_removes_only_their_lines() {
        let existing = b"# c\nTG_API_ID=1\nexport TEAGARDEN_SESSION_PATH = /a\r\nBIN=\xff\nTEAGARDEN_VOLUMES_DIR=/v\nTG_API_HASH=h";
        let out = drop_keys(
            existing,
            &["TEAGARDEN_SESSION_PATH", "TEAGARDEN_VOLUMES_DIR"],
        );
        assert_eq!(out, b"# c\nTG_API_ID=1\nBIN=\xff\nTG_API_HASH=h");
        // Nothing to drop: byte for byte the same, even without a final newline.
        assert_eq!(drop_keys(&out, &["NOPE"]), out);
        assert_eq!(drop_keys(b"", &["X"]), b"");
    }

    #[test]
    fn env_value_reads_the_last_assignment_of_a_key() {
        let env = b"A=1\nexport K = /one\r\nB=2\nK=/two\n";
        assert_eq!(env_value(env, "K").as_deref(), Some("/two"));
        assert_eq!(env_value(env, "A").as_deref(), Some("1"));
        assert_eq!(env_value(env, "NOPE"), None);
        assert_eq!(env_value(b"K=\n", "K"), None, "an empty value is unset");
        assert_eq!(env_value(b"K=\xff\n", "K"), None, "not UTF-8");
    }
}
